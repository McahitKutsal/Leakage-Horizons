r"""The manuscript's house style for figures, in one place.

The seven figures were drawn by hand in a diagram editor and the numbers in them were typed from the
artefacts. That is two copies of every series, and D-46 records what it cost: Figure 3's panel A carried
a legibility offset that a reader correctly read as a decline the data do not contain, and Figure 2's
upper-bound row named the wrong two settings. Neither could be caught by a checker, because a checker
compares text against artefacts and a drawing is neither.

`scripts/build_figures.py` draws them from `results/` instead, so the manuscript's claim that every
figure is regenerated by a named script becomes true rather than aspirational, and a series can no
longer disagree with the artefact it came from. This module holds only the shared style, so that a
change to the palette or the type is one edit rather than seven.

The palette is the one the hand-drawn figures used, read off their sources: a blue-grey ramp with no
hue carrying meaning anywhere. Series are separated by weight, dash pattern and marker shape, which is
what makes the set printable in one ink and legible to a reader who cannot distinguish colours. The two
darkest inks are reserved for data; everything lighter is structure.
"""
from __future__ import annotations

import matplotlib as mpl
import matplotlib.pyplot as plt

__all__ = ["INK", "SERIES", "use_house_style", "panel", "direct_label", "save"]

# Read off the hand-drawn sources. Named by role rather than by shade so a later palette change cannot
# silently swap a data ink for a guide ink.
INK = {
    "data_primary": "#14202C",     # the target relation, and any series carrying the argument
    "data_secondary": "#33465A",
    "data_tertiary": "#5A6B7C",
    "annotation": "#6E6A87",       # callouts and measures
    "guide": "#7A8B9C",            # leader lines, reference lines
    "axis": "#5A6B7C",
    "grid": "#CBD7E2",
    "band": "#D6DEE6",             # shaded intervals and ribbons
    "fill_light": "#E4EAEF",
    "accent": "#4A7A9C",           # used twice in Figure 1 and nowhere else
}

# Weight, dash and marker per series role. A reader should be able to tell any two apart with the ink
# removed, which is the greyscale requirement stated in Figure 1's specification.
SERIES = {
    "target":   dict(color=INK["data_primary"], lw=1.9, ls="-", marker="o", ms=4.0,
                     markerfacecolor=INK["data_primary"]),
    "anchor_a": dict(color=INK["data_secondary"], lw=1.3, ls=(0, (5, 2)), marker="s", ms=3.6,
                     markerfacecolor="white"),
    "anchor_b": dict(color=INK["data_tertiary"], lw=1.3, ls=(0, (5, 2)), marker="^", ms=4.0,
                     markerfacecolor="white"),
    "other":    dict(color=INK["data_tertiary"], lw=1.0, ls=(0, (1.5, 1.5)), marker="", ms=0),
    "flat":     dict(color=INK["data_tertiary"], lw=1.0, ls=(0, (1, 1.6)), marker="D", ms=2.8,
                     markerfacecolor="white"),
}

BASE_FONT = 8.4


def use_house_style() -> None:
    """Set the rc parameters every figure in the manuscript shares.

    Times New Roman with a stack behind it: the journal's template is a serif and a figure that falls
    back to a sans on another machine looks like a different paper's figure.
    """
    mpl.rcParams.update({
        "font.family": "serif",
        "font.serif": ["Times New Roman", "Nimbus Roman", "DejaVu Serif", "serif"],
        "mathtext.fontset": "dejavuserif",
        "font.size": BASE_FONT,
        "axes.labelsize": BASE_FONT,
        "axes.titlesize": BASE_FONT + 0.8,
        "xtick.labelsize": BASE_FONT - 0.6,
        "ytick.labelsize": BASE_FONT - 0.6,
        "axes.edgecolor": INK["axis"],
        "axes.linewidth": 0.7,
        "axes.labelcolor": INK["data_secondary"],
        "text.color": INK["data_secondary"],
        "xtick.color": INK["axis"],
        "ytick.color": INK["axis"],
        "xtick.major.width": 0.7,
        "ytick.major.width": 0.7,
        "xtick.major.size": 2.6,
        "ytick.major.size": 2.6,
        "xtick.direction": "out",
        "ytick.direction": "out",
        "legend.frameon": False,
        "legend.fontsize": BASE_FONT - 0.8,
        "figure.facecolor": "white",
        "savefig.facecolor": "white",
        "savefig.bbox": "tight",
        "savefig.pad_inches": 0.02,
        "svg.fonttype": "none",     # keep text as text, so the journal can restyle it
        "pdf.fonttype": 42,
    })


def panel(ax, *, title: str | None = None, xlabel: str | None = None, ylabel: str | None = None,
          grid: str = "y") -> None:
    """Strip an axis down to the house minimum: two spines, faint grid, no box."""
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    if grid in ("y", "both"):
        ax.yaxis.grid(True, color=INK["grid"], lw=0.5, alpha=0.9)
    if grid in ("x", "both"):
        ax.xaxis.grid(True, color=INK["grid"], lw=0.5, alpha=0.9)
    ax.set_axisbelow(True)
    if title:
        ax.set_title(title, loc="left", color=INK["data_secondary"], pad=4)
    if xlabel:
        ax.set_xlabel(xlabel)
    if ylabel:
        ax.set_ylabel(ylabel)


def direct_label(ax, x, y, text, *, color=None, ha="left", va="center", size=None, **kw):
    """Label a series where it ends rather than in a legend.

    The manuscript's figure specifications ask for this repeatedly and the reason is worth keeping in
    the code: a legend makes the reader carry a mapping across the panel, and these panels are small.
    """
    return ax.annotate(text, (x, y), color=color or INK["data_secondary"], ha=ha, va=va,
                       fontsize=size or BASE_FONT - 0.6, annotation_clip=False, **kw)


def save(fig, out_dir, stem: str) -> list:
    """Write one figure as SVG for the manuscript, PDF for the publisher, PNG as a raster fallback.

    Word renders the SVG through the `svgBlip` extension and falls back to the raster on anything
    older, which is the pairing the authors' own document already uses. The PDF is what an Elsevier
    submission actually wants.
    """
    written = []
    for ext, kw in (("svg", {}), ("pdf", {}), ("png", {"dpi": 600})):
        p = out_dir / f"{stem}.{ext}"
        fig.savefig(p, **kw)
        written.append(p)
    plt.close(fig)
    return written
